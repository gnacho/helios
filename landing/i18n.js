function detectLang() {
  const url = new URLSearchParams(location.search).get('hl')
  if (url === 'es' || url === 'en') return url
  const saved = localStorage.getItem('helios-lang')
  if (saved === 'es' || saved === 'en') return saved
  return navigator.language && navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en'
}

function applyLang(lang) {
  const dict = I18N[lang]
  document.documentElement.lang = lang
  document.documentElement.dataset.lang = lang
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n
    if (dict[key]) el.innerHTML = dict[key]
  })
  document.querySelectorAll('img[data-lang-src-en]').forEach((img) => {
    const en = img.dataset.langSrcEn
    if (lang === 'en' && en) img.src = en
  })
  const btn = document.getElementById('langBtn')
  if (btn) btn.textContent = lang === 'es' ? 'EN' : 'ES'
  localStorage.setItem('helios-lang', lang)
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }))
}

window.heliosI18n = { detectLang, applyLang, I18N }
